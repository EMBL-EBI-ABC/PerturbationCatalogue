#!/usr/bin/env python3
"""Validate fitted MAVE scores against internal controls, ClinVar and GWAS.

Python implementation of ``analysis/mave_gmm_validation.R``. All inputs are
local: native modes GMM batches, canonical metadata/scores and generated variant
TSVs. No model fitting or reference downloads are performed.
"""

from __future__ import annotations

import argparse
import importlib.metadata
import logging
import sys
import tempfile
from pathlib import Path
from typing import Any, Sequence

import pandas as pd

REPOSITORY_ROOT = Path(__file__).resolve().parents[3]
if str(REPOSITORY_ROOT) not in sys.path:
    sys.path.insert(0, str(REPOSITORY_ROOT))

from data_sources.mavedb.analysis._homology_inputs import input_fingerprint
from data_sources.mavedb.analysis._reference_io import (
    positive_int,
    publish_tables,
    write_json,
)
from data_sources.mavedb.analysis._validation_core import evaluate_validation
from data_sources.mavedb.analysis._validation_inputs import load_inputs

LOGGER = logging.getLogger("mave_gmm_validation")
MAVEDB_ROOT = REPOSITORY_ROOT / "data_sources" / "mavedb"
MANIFEST = "manifest.json"
TABLE_NAMES = (
    "controls",
    "clinvar_matches",
    "gwas_matches",
    "ctrl_roc",
    "clinvar_roc",
    "gwas_roc",
    "auc_summary",
    "counts",
)
FIGURE_NAMES = (
    "distributions",
    "control_distribution",
    "control_roc_curves",
    "control_auc_distribution",
    "clinvar_distribution",
    "clinvar_roc_curves",
    "clinvar_auc_distribution",
    "gwas_distribution",
    "gwas_roc_curves",
    "gwas_auc_distribution",
)


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--gmm-dir",
        type=Path,
        required=True,
        help=(
            "Collected GMM model directory, its merged/ subdirectory, or a "
            "legacy indexed batch directory"
        ),
    )
    parser.add_argument(
        "--metadata",
        type=Path,
        default=MAVEDB_ROOT / "output/processed/metadata.tsv",
        help="Canonical processed metadata TSV",
    )
    parser.add_argument(
        "--source-scores",
        type=Path,
        default=MAVEDB_ROOT / "output/processed/scores.tsv",
        help="Canonical scores TSV used to recover WT flags by source-row identity",
    )
    parser.add_argument(
        "--clinvar",
        type=Path,
        default=MAVEDB_ROOT / "output/variant_data/mave_clinvar_variants.tsv",
        help="ClinVar TSV generated by process_variant_data.py",
    )
    parser.add_argument(
        "--gwas",
        type=Path,
        default=MAVEDB_ROOT / "output/variant_data/mave_gwas_variants.tsv",
        help="GWAS TSV generated by process_variant_data.py",
    )
    parser.add_argument(
        "--out", type=Path, default=MAVEDB_ROOT / "output/gmm_validation"
    )
    parser.add_argument(
        "--formats", choices=("png", "pdf"), nargs="+", default=["png", "pdf"]
    )
    parser.add_argument("--dpi", type=positive_int, default=150)
    parser.add_argument("--no-plots", action="store_true")
    return parser


def _managed_paths() -> set[Path]:
    return (
        {Path(f"{name}.tsv") for name in TABLE_NAMES}
        | {
            Path("figures") / f"{name}.{extension}"
            for name in FIGURE_NAMES
            for extension in ("png", "pdf")
        }
        | {Path(MANIFEST)}
    )


def _write_table(frame: pd.DataFrame, path: Path) -> None:
    """Keep nullable metrics and R-compatible logical values in TSV exports."""
    exported = frame.copy()
    for column in exported.columns:
        if pd.api.types.is_bool_dtype(exported[column].dtype):
            exported[column] = exported[column].map({True: "TRUE", False: "FALSE"})
    exported.to_csv(path, sep="\t", index=False, na_rep="NA")


def _coverage_warnings(tables: dict[str, pd.DataFrame]) -> list[str]:
    warnings = []
    if tables["controls"].empty:
        warnings.append("No internal controls were identified in the fitted scores.")
    if tables["clinvar_matches"].empty:
        warnings.append("No direct ClinVar variants match the fitted scores.")
    elif tables["clinvar_roc"].empty:
        warnings.append("Matched ClinVar labels do not support binary evaluation.")
    if tables["gwas_roc"].empty:
        warnings.append("No human fitted score sets contain a matching GWAS hit.")
    summary = tables["auc_summary"]
    if not summary.empty and summary["auc"].isna().any():
        warnings.append(
            "Some ROC AUCs are undefined; inspect class counts and predictor coverage."
        )
    for warning in warnings:
        LOGGER.warning(warning)
    return warnings


def run(args: argparse.Namespace) -> dict[str, pd.DataFrame]:
    """Compute fresh results and publish them with rollback on write failure."""
    inputs = load_inputs(
        metadata=args.metadata,
        gmm_dir=args.gmm_dir,
        source_scores=args.source_scores,
        clinvar=args.clinvar,
        gwas=args.gwas,
    )
    managed = _managed_paths()
    input_paths = {path.resolve() for path in inputs.paths}
    if overlap := {args.out.resolve() / name for name in managed} & input_paths:
        raise ValueError(f"Output would overwrite an input file: {sorted(overlap)[0]}")
    tables = evaluate_validation(
        scores=inputs.scores,
        params=inputs.params,
        meta=inputs.meta,
        clinvar=inputs.clinvar,
        gwas=inputs.gwas,
    )
    warnings = _coverage_warnings(tables)
    fitted_urns = sorted(inputs.scores["score_urn"].dropna().unique().tolist())
    LOGGER.info(
        "Validating %d fitted score sets, %d observations; %d ClinVar matches, "
        "%d GWAS matched/unmatched rows",
        len(fitted_urns),
        len(inputs.scores),
        len(tables["clinvar_matches"]),
        len(tables["gwas_matches"]),
    )
    implementation_paths = [Path(__file__)] + [
        Path(__file__).parent / name
        for name in (
            "_validation_inputs.py",
            "_validation_core.py",
            "_validation_plots.py",
            "_homology_inputs.py",
            "_homology_clinvar.py",
            "_reference_io.py",
            "mave_summary/data.py",
            "_mave_qc.py",
            "../scripts/process_mavedb.py",
        )
    ]
    manifest: dict[str, Any] = {
        "schema_version": 1,
        "source": "ot_perturbation_catalog_mave_experiments/analysis/mave_gmm_validation.R",
        "inputs": input_fingerprint(inputs.paths),
        "implementation": input_fingerprint(implementation_paths),
        "versions": {
            name: importlib.metadata.version(name)
            for name in ("numpy", "pandas", "scipy", "matplotlib")
        },
        "input_coverage": {
            "eligible_metadata_score_sets": len(inputs.meta),
            "fitted_score_sets": len(fitted_urns),
            "fitted_score_urns": fitted_urns,
            "fitted_observations": len(inputs.scores),
            "combined_clinvar_variants": len(inputs.clinvar),
            "gwas_reference_rows": len(inputs.gwas),
        },
        "settings": {
            "plots": not args.no_plots,
            "formats": list(dict.fromkeys(args.formats)) if not args.no_plots else [],
            "dpi": args.dpi,
        },
        "semantics": {
            "auc": "R-compatible left-step integration",
            "pr_x_axis": "recall (corrects FPR used in the R figure code)",
            "gwas_negative_class": "unmatched variant, not established neutrality",
            "gwas_cache": "recomputed from current inputs on every run",
            "observations": "individual source rows; GWAS many-to-many joins retained",
        },
        "warnings": warnings,
        "tables": {name: len(tables[name]) for name in TABLE_NAMES},
    }
    args.out.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(
        prefix=".mave-gmm-validation-", dir=args.out.parent
    ) as directory:
        staged = Path(directory)
        for name in TABLE_NAMES:
            _write_table(tables[name], staged / f"{name}.tsv")
        if not args.no_plots:
            import matplotlib.pyplot as plt

            from data_sources.mavedb.analysis._validation_plots import (
                build_plots,
                save_plots,
            )

            figures = build_plots(tables)
            try:
                save_plots(
                    figures,
                    staged / "figures",
                    formats=tuple(dict.fromkeys(args.formats)),
                    dpi=args.dpi,
                )
            finally:
                for figure in figures.values():
                    plt.close(figure)
        manifest["files"] = sorted(
            [MANIFEST]
            + [
                path.relative_to(staged).as_posix()
                for path in staged.rglob("*")
                if path.is_file()
            ]
        )
        write_json(staged / MANIFEST, manifest)
        publish_tables(staged, args.out, manifest=MANIFEST, managed=managed)
    LOGGER.info("Saved validation tables and reports to %s", args.out)
    return tables


def main(argv: Sequence[str] | None = None) -> int:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s: %(message)s")
    args = _parser().parse_args(argv)
    try:
        run(args)
    except (OSError, ValueError, pd.errors.ParserError) as exc:
        LOGGER.error("GMM validation failed: %s", exc)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
